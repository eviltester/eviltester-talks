      ## Blurb
    </p>
    <p>
      
    </p>
    <p>
      We will also take stock of our current ability and build an action plan to improve our test ability.
    </p>
    <p>
      
    </p>
    <p>
      This workshop has elements of discussion, hands on investigation and hands on testing.
    </p>
    <p>
      
    </p>
