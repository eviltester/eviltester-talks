    <p>
      
    </p>
    <p>
      # What is Agile?
    </p>
    <p>
      
    </p>
    <p>
      A series of question exercises for you to model Agile and Agile Testing in your own words.
    </p>
    <p>
      
    </p>
    <p>
      The aim is to build a model of Agile and Testing within Agile.
    </p>
    <p>
      
    </p>
    <p>
      Not to build a definition.
    </p>
    <p>
      
    </p>
    <p>
      Definitions are hard to get 'right' and they are hard to change. We associate a definition with a 'fixed' point.
    </p>
    <p>
      
    </p>
    <p>
      Models are easy to change, we learn more information, we adapt the model to fit the information.
    </p>
    <p>
      
    </p>
    <p>
      Build a model, as it is easier to expand.
    </p>
  </body>
</html>

