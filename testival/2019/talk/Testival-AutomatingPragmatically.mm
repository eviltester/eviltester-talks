    <p>
      # Models of Automated Execution
    </p>
    <p>
      
    </p>
    <p>
      - System as a Graph
    </p>
    <p>
      - Paths through a System
    </p>
    <p>
      - Data flows through paths
    </p>
    <p>
      - Invariant Data Controls Paths
    </p>
    <p>
      - Variant Data
    </p>
    <p>
      &#160;&#160;&#160;&#160;- Partitions
    </p>
    <p>
      &#160;&#160;&#160;&#160;- Abstracted
    </p>
    <p>
      
    </p>
    <p>
      ---
    </p>
    <p>
      
    </p>
    <p>
      # System as a Graph
    </p>
    <p>
      
    </p>
    <p>
      - there are many executable models
    </p>
    <p>
      &#160;&#160;&#160;&#160;- events, state, flow
    </p>
    <p>
      - model based testing
    </p>
    <p>
      &#160;&#160;&#160;&#160;- all testing is model based
    </p>
    <p>
      &#160;&#160;&#160;&#160;- execution can be model driven
    </p>
    <p>
      
    </p>
    <p>
      ---
    </p>
    <p>
      
    </p>
    <p>
      # Paths through a System
    </p>
    <p>
      
    </p>
    <p>
      - execution follows a path
    </p>
    <p>
      - manually
    </p>
    <p>
      &#160;&#160;&#160;&#160;- via test script
    </p>
    <p>
      &#160;&#160;&#160;&#160;- exploratory objective
    </p>
    <p>
      - automated
    </p>
    <p>
      &#160;&#160;&#160;&#160;- code
    </p>
    <p>
      &#160;&#160;&#160;&#160;- model traversal
    </p>
    <p>
      &#160;&#160;&#160;&#160;- keywords
    </p>
    <p>
      &#160;&#160;&#160;&#160;- declarative implementation (BDD)
    </p>
    <p>
      
    </p>
    <p>
      Flow abstraction.
    </p>
    <p>
      
    </p>
    <p>
      ---
    </p>
    <p>
      
    </p>
    <p>
      # Data Flows Through Paths
    </p>
    <p>
      
    </p>
    <p>
      - Login (username, password),
    </p>
    <p>
      - Create New User (username, email, role)
    </p>
    <p>
      
    </p>
    <p>
      Gives us:
    </p>
    <p>
      
    </p>
    <p>
      - Data Driven Testing
    </p>
    <p>
      - BDD example tables
    </p>
    <p>
      - Certain paths require Invariant data (admin role)
    </p>
    <p>
      - Equivalence Partitions (valid email, invalid email)
    </p>
    <p>
      
    </p>
    <p>
      ---
    </p>
    <p>
      
    </p>
    <p>
      # From Modelling, comes Coverage
    </p>
    <p>
      
    </p>
    <p>
      ---
    </p>
    <p>
      
    </p>
    <p>
      # Automate Tactically or Strategically
    </p>
    <p>
      
    </p>
    <p>
      - Strategically
    </p>
    <p>
      &#160;&#160;&#160;&#160;- long term,
    </p>
    <p>
      &#160;&#160;&#160;&#160;- team agreed,
    </p>
    <p>
      &#160;&#160;&#160;&#160;- maintained,
    </p>
    <p>
      &#160;&#160;&#160;&#160;- specific tools
    </p>
    <p>
      - Tactically
    </p>
    <p>
      &#160;&#160;&#160;&#160;- short term,
    </p>
    <p>
      &#160;&#160;&#160;&#160;- specific objective,
    </p>
    <p>
      &#160;&#160;&#160;&#160;- single use/person,
